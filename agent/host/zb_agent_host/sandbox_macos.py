"""macOS Seatbelt backend (MS6) — the profile generator.

`render_profile` emits the Seatbelt (.sb) text a `MacSeatbeltBackend` launch runs under
`/usr/bin/sandbox-exec -f <profile> -D ...`. It realizes, in profile form, the same semantic launch
contract the Linux `LinuxBwrapBackend` realizes as a bwrap argv (MS0 `SandboxBackend`): deny-default,
a read-only workspace with a writable scratchpad, and the backend's network capability (the egress
endpoint for the CLI/helper, the two bridge ports, and hooks reaching the bridges only).

The security-load-bearing rules were measured against the real kernel on both arches in the MS6.1 gate
(tests/mac/ms6_1_token_isolation_test.sh):
  - cross-process `kern.procargs2` (a token on the CLI's command line / env) is kept out ONLY by BOTH a
    CURATED `sysctl-read` allowlist (a blanket `(allow sysctl-read)` re-opens it) AND an EXPLICIT
    `(deny process-info*)` ((deny default) alone does not cover it; the sysctl is a numeric MIB with no
    string name, so it can't be named directly);
  - the task port is never granted (`task_for_pid` is also system-denied, but we never ask).

Reads are still broad here (deny-default read curation is a separate later MS6 increment); that does not
affect token isolation, which is about the CLI *process*, not files. Pure stdlib so it unit-tests on Linux.
"""

# Standard character devices a process needs to be writable to run (as the containment spike).
_CHAR_DEVICES = ("/dev/null", "/dev/zero", "/dev/dtracehelper", "/dev/tty", "/dev/urandom", "/dev/random")

# Curated sysctl-read allowlist — enough for a process to start, and deliberately NOT a blanket
# (allow sysctl-read), which (measured, MS6.1) re-opens another process's kern.procargs2 even with
# process-info denied. kern.procargs2 is a numeric MIB with no string name, so it is excluded by omission.
_SYSCTL_ALLOW = (
    ("sysctl-name-prefix", "hw."),
    ("sysctl-name-prefix", "kern.os"),
    ("sysctl-name", "kern.ostype"),
    ("sysctl-name", "kern.osrelease"),
    ("sysctl-name", "kern.version"),
    ("sysctl-name", "kern.hostname"),
    ("sysctl-name", "kern.maxproc"),
    ("sysctl-name", "kern.argmax"),
    ("sysctl-name", "kern.ngroups"),
    ("sysctl-name", "kern.usrstack64"),
)


def render_profile(*, scratchpad, workspace, egress, bridges, is_hook):
    """Return the Seatbelt profile text for a CLI/helper (``is_hook=False``) or a hook (``is_hook=True``).

    ``scratchpad`` is the only writable subpath; ``workspace`` is read-only input (never written — a direct
    write bypasses the broker and must fail closed, so it is kept out of every write rule). ``egress`` is a
    :class:`sandbox.Endpoint` (or None); ``bridges`` is the tuple of loopback bridge ports. A hook reaches
    the bridges ONLY — never the egress endpoint (rev 16.2 §3c).
    """
    net = [f'(remote ip "localhost:{p}")' for p in bridges]
    if not is_hook and egress is not None:
        net.insert(0, f'(remote ip "localhost:{egress.port}")')

    # The first sysctl filter sits on the (allow sysctl-read ...) line itself, so the rule is unmistakably
    # curated (filtered), never a bare blanket allow.
    first_k, first_v = _SYSCTL_ALLOW[0]
    sysctl_lines = [f'(allow sysctl-read ({first_k} "{first_v}")']
    for k, v in _SYSCTL_ALLOW[1:]:
        sysctl_lines.append(f'  ({k} "{v}")')
    sysctl_lines[-1] += ")"

    devices = " ".join(f'(literal "{d}")' for d in _CHAR_DEVICES)
    kind = "hook" if is_hook else "cli/helper"
    net_note = "bridges only (no egress — rev 16.2 §3c)" if is_hook else "egress + bridges"

    lines = [
        "(version 1)",
        f";; MS6 macOS Seatbelt profile ({kind}) — generated by sandbox_macos.render_profile. Do not hand-edit.",
        f";; workspace (read-only input): {workspace}",
        "(deny default)",
        "(allow process-fork)",
        "(allow process-exec)",
        "(allow file-read*)",  # broad reads (read curation is a later MS6 increment); workspace is readable
        "(allow file-write*",
        f'  (subpath "{scratchpad}")',
        f"  {devices})",
        f";; network: {net_note}",
        f"(allow network-outbound {' '.join(net)})",
        ";; sysctl-read CURATED (MS6.1): never blanket — a blanket allow re-opens kern.procargs2.",
        *sysctl_lines,
        ";; token isolation (MS6.1): explicit process-info deny; the task port is never granted.",
        "(deny process-info*)",
        "(allow mach-lookup)",  # tiny curated mach-lookup is a separate later MS6 increment
    ]
    return "\n".join(lines) + "\n"
