"""4pa.66 (plan R29-MS6 D2, R30-MS6): the Python half of the registered seatbelt readiness invariant.

Imports the PRODUCTION profile generator (`zb_agent_host.sandbox_macos`), renders every profile it can emit, reads
its readiness source (`PROFILE_CURATION`) and its derived `LAUNCH_SPEC_CONSUMABLE`, and writes them as a Zig
source file (argv[1]) that `tests/agent_seatbelt_readiness_invariant_test.zig` imports as `seatbelt_facts`. The
invariant itself is judged on the Zig side, beside `agent_setup.seatbelt_ready`, so the two languages are compared
in one test. A missing source is written as null (never a crash), so the red fails at its stated assertion.

Run:  python3 seatbelt_readiness_facts.py <out.zig>   (zig build test-agent-seatbelt-readiness runs it)
"""
import sys
from pathlib import Path

HOST_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HOST_DIR))

from zb_agent_host import sandbox, sandbox_macos  # noqa: E402

_EGRESS = sandbox.Endpoint("127.0.0.1", 52346)
_BRIDGES = sandbox_macos.CANONICAL_BRIDGES


def _zig_string(text):
    """`text` as a Zig string literal: printable ASCII as is, every other byte as \\xNN (no escape can drift)."""
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch in '\\"':
            out.append("\\" + ch)
        elif 0x20 <= byte <= 0x7E:
            out.append(ch)
        else:
            out.append(f"\\x{byte:02x}")
    return '"' + "".join(out) + '"'


def _profiles():
    """Every profile the generator emits: the CLI/helper, a hook, the sign-in, and setup's own runs."""
    return (
        ("cli/helper", sandbox_macos.render_profile(egress=_EGRESS, bridges=_BRIDGES, is_hook=False)),
        ("hook", sandbox_macos.render_profile(egress=None, bridges=_BRIDGES, is_hook=True)),
        ("login", sandbox_macos.render_profile(egress=_EGRESS, bridges=(), is_hook=False, is_login=True)),
        ("setup", sandbox_macos.render_setup_profile()),
        ("setup+r1", sandbox_macos.render_setup_profile(loopback_port=52347)),
    )


def _readiness():
    """(curation name or None, kind of LAUNCH_SPEC_CONSUMABLE, its value)."""
    curation = getattr(sandbox_macos, "PROFILE_CURATION", None)
    name = getattr(curation, "name", None)
    consumable = getattr(sandbox_macos, "LAUNCH_SPEC_CONSUMABLE", None)
    if consumable is None:
        return name, "absent", False
    if callable(consumable):
        return name, "function", consumable() is True
    return name, "bool", consumable is True


def render(out):
    name, kind, value = _readiness()
    curated_name = getattr(getattr(sandbox_macos, "Curation", None), "CURATED", None)
    lines = [
        "// Generated by agent/host/tests/seatbelt_readiness_facts.py from the production sandbox_macos. Do not edit.",
        "pub const Profile = struct { name: []const u8, text: []const u8 };",
        f"pub const curation: ?[]const u8 = {'null' if name is None else _zig_string(name)};",
        f"pub const curated_name: ?[]const u8 = {'null' if curated_name is None else _zig_string(curated_name.name)};",
        f"pub const launch_spec_consumable_kind: []const u8 = {_zig_string(kind)};",
        f"pub const launch_spec_consumable: bool = {'true' if value else 'false'};",
        "pub const profiles = [_]Profile{",
    ]
    lines += [f"    .{{ .name = {_zig_string(n)}, .text = {_zig_string(t)} }}," for n, t in _profiles()]
    lines.append("};")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: seatbelt_readiness_facts.py <out.zig>")
    render(Path(sys.argv[1]))
