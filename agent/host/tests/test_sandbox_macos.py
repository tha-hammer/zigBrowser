EGRESS = sandbox.Endpoint("127.0.0.1", 52346)
BRIDGES = (51091, 31337)
_DEVICES = ('(literal "/dev/null") (literal "/dev/zero") (literal "/dev/dtracehelper") '
            '(literal "/dev/tty") (literal "/dev/urandom") (literal "/dev/random")')


def reference_profile(*, egress, bridges, is_hook, is_login=False):
    """A frozen, independent re-statement of the expected profile text. A policy change must update this in
    the same commit (the point of a frozen golden); a generator mutant diverges from it."""
    if is_login:
        eps = [f"localhost:{egress.port}"]
    else:
        eps = ([] if is_hook else [f"localhost:{egress.port}"]) + [f"localhost:{p}" for p in bridges]
    net = " ".join(f'(remote ip "{e}")' for e in eps)
    kind = "login" if is_login else ("hook" if is_hook else "cli/helper")
    note = ("egress only (sign-in; no bridges)" if is_login
            else "bridges only (no egress — rev 16.2 §3c)" if is_hook else "egress + bridges")
    return "\n".join([
        "(version 1)",
        f";; MS6 macOS Seatbelt profile ({kind}) — generated by sandbox_macos.render_profile. Do not hand-edit.",
        ";; The writable path is the SCRATCHPAD -D parameter; no untrusted value is interpolated into source.",
        "(deny default)",
        "(allow process-fork)",
        "(allow process-exec)",
        "(allow file-read*)",
        f'(allow file-write* (subpath (param "SCRATCHPAD")) {_DEVICES})',
        f";; network: {note}",
        f"(allow network-outbound {net})",
        ";; sysctl-read CURATED (MS6.1): never blanket — a blanket allow re-opens kern.procargs2.",
        '(allow sysctl-read (sysctl-name-prefix "hw.")',
        '  (sysctl-name-prefix "kern.os")',
        '  (sysctl-name "kern.ostype")',
        '  (sysctl-name "kern.osrelease")',
        '  (sysctl-name "kern.version")',
        '  (sysctl-name "kern.hostname")',
        '  (sysctl-name "kern.maxproc")',
        '  (sysctl-name "kern.argmax")',
        '  (sysctl-name "kern.ngroups")',
        '  (sysctl-name "kern.usrstack64"))',
        ";; token isolation (MS6.1): explicit process-info deny; the task port is never granted.",
        "(deny process-info*)",
        "(allow mach-lookup)",
    ]) + "\n"


class ProfileEqualsFrozenReference(unittest.TestCase):
    def test_cli_profile_matches_reference(self):
        self.assertEqual(sandbox_macos.render_profile(egress=EGRESS, bridges=BRIDGES, is_hook=False),
                         reference_profile(egress=EGRESS, bridges=BRIDGES, is_hook=False))

    def test_hook_profile_matches_reference(self):
        self.assertEqual(sandbox_macos.render_profile(egress=None, bridges=BRIDGES, is_hook=True),
                         reference_profile(egress=None, bridges=BRIDGES, is_hook=True))

    def test_oracle_rejects_a_wrong_profile(self):
        """Anti-tautology: a profile missing the process-info deny must NOT equal the reference."""
        mutant = reference_profile(egress=EGRESS, bridges=BRIDGES, is_hook=False).replace(
            "(deny process-info*)\n", "")
        self.assertNotEqual(mutant, reference_profile(egress=EGRESS, bridges=BRIDGES, is_hook=False),
                            "the frozen reference must distinguish a profile that dropped (deny process-info*)")

    def test_login_profile_matches_reference(self):
        # The sign-in profile is egress-only (no bridges).
        self.assertEqual(sandbox_macos.render_profile(egress=EGRESS, bridges=(), is_hook=False, is_login=True),
                         reference_profile(egress=EGRESS, bridges=(), is_hook=False, is_login=True))

    def test_login_profile_is_egress_only(self):
        p = sandbox_macos.render_profile(egress=EGRESS, bridges=(), is_hook=False, is_login=True)
        self.assertIn(f'(remote ip "localhost:{EGRESS.port}")', p)
        for port in BRIDGES:
            self.assertNotIn(f"localhost:{port}", p, "the login profile has NO bridges")
        self.assertIn("(deny process-info*)", p)  # the token-isolation belt still holds

    def test_login_validation(self):
        with self.assertRaises(ValueError):  # login needs egress
            sandbox_macos.render_profile(egress=None, bridges=(), is_hook=False, is_login=True)
        with self.assertRaises(ValueError):  # login has no bridges
            sandbox_macos.render_profile(egress=EGRESS, bridges=BRIDGES, is_hook=False, is_login=True)
        with self.assertRaises(ValueError):  # login is not a hook
            sandbox_macos.render_profile(egress=EGRESS, bridges=(), is_hook=True, is_login=True)
        with self.assertRaises(ValueError):  # is_login must be a bool
            sandbox_macos.render_profile(egress=EGRESS, bridges=BRIDGES, is_hook=False, is_login=0)


class NoUntrustedInterpolation(unittest.TestCase):
    """RoseCat 6918 #1: the writable path is a -D param, never interpolated; the workspace is never written."""

    def test_scratchpad_is_a_named_param_not_a_path(self):
        p = sandbox_macos.render_profile(egress=EGRESS, bridges=BRIDGES, is_hook=False)
        self.assertIn('(subpath (param "SCRATCHPAD"))', p, "the scratchpad must be a -D param")
        # No write rule names a concrete absolute path (which would mean an interpolated, injectable value).
        self.assertNotIn('(subpath "/', p, "no write rule may interpolate a concrete path")

    def test_render_profile_takes_no_path_argument(self):
        # A path cannot be injected because render_profile does not accept one; it is bound via dparams/-D.
        import inspect
        params = set(inspect.signature(sandbox_macos.render_profile).parameters)
        self.assertEqual(params, {"egress", "bridges", "is_hook", "is_login"},
                         "render_profile's signature is EXACTLY these — no untrusted path/string channel may be "
                         "added (RoseCat 6989: a weaker name-filter would let a future `source`/`root`/`home` slip in)")

    def test_dparams_validates_absolute_scratchpad(self):
        self.assertEqual(sandbox_macos.dparams(scratchpad="/zb/dist/current/state/scratchpad"),
                         {"SCRATCHPAD": "/zb/dist/current/state/scratchpad"})
        # RoseCat 6939 #1: the scratchpad is the SOLE write grant, so root / aliases that resolve to root or
        # elsewhere must be refused, or the write grant widens.
        for bad in ("relative/path", "", 'has"quote', None, "/", "/tmp/..", "/a/../b", "/tmp/", "/a/./b", "//tmp"):
            with self.assertRaises(ValueError):
                sandbox_macos.dparams(scratchpad=bad)


class NetworkCapabilityValidated(unittest.TestCase):
    """RoseCat 6918 #2/#3: empty/malformed capabilities are REFUSED, never widened; values are validated."""

    def test_empty_bridges_refused(self):
        for is_hook, egress in ((True, None), (False, EGRESS)):
            with self.assertRaises(ValueError):
                sandbox_macos.render_profile(egress=egress, bridges=(), is_hook=is_hook)

    def test_cli_without_egress_refused(self):
        with self.assertRaises(ValueError):
            sandbox_macos.render_profile(egress=None, bridges=BRIDGES, is_hook=False)

    def test_hook_with_egress_refused(self):
        with self.assertRaises(ValueError):
            sandbox_macos.render_profile(egress=EGRESS, bridges=BRIDGES, is_hook=True)

    def test_bad_ports_refused(self):
        for bad in (0, 65536, -1, "80", 1.5, True):
            with self.assertRaises(ValueError):
                sandbox_macos.render_profile(egress=sandbox.Endpoint("127.0.0.1", bad),
                                             bridges=BRIDGES, is_hook=False)
            with self.assertRaises(ValueError):
                sandbox_macos.render_profile(egress=EGRESS, bridges=(bad, 31337), is_hook=False)

    def test_non_loopback_host_refused(self):
        # RoseCat 6939 #3: the egress host must be EXACTLY 127.0.0.1 — "localhost" (a name) is refused too.
        for host in ("localhost", "evil.example", "0.0.0.0", '127.0.0.1"))\n(allow network*'):
            with self.assertRaises(ValueError):
                sandbox_macos.render_profile(egress=sandbox.Endpoint(host, 52346),
                                             bridges=BRIDGES, is_hook=False)

    def test_bridges_must_be_exactly_the_two_canonical_ports(self):
        # RoseCat 6939 #3: missing, extra, wrong, or duplicate bridges are refused (plan :1581-1593).
        for bad in ((51091,), (31337,), (51091, 31337, 4444), (51091, 9999), (51091, 51091), (31337, 51091, 31337)):
            for is_hook, egress in ((False, EGRESS), (True, None)):
                with self.assertRaises(ValueError):
                    sandbox_macos.render_profile(egress=egress, bridges=bad, is_hook=is_hook)

    def test_is_hook_must_be_a_bool(self):
        # RoseCat 6939 #2: a non-bool (0 is falsy -> would wrongly get egress) is refused.
        for bad in (0, 1, None, "true", "", []):
            with self.assertRaises(ValueError):
                sandbox_macos.render_profile(egress=EGRESS, bridges=BRIDGES, is_hook=bad)

    def test_duplicate_endpoints_refused(self):
        with self.assertRaises(ValueError):
            sandbox_macos.render_profile(egress=EGRESS, bridges=(51091, 51091), is_hook=False)

    def test_no_empty_network_allow_is_ever_emitted(self):
        # The dangerous Seatbelt shape (allow network-outbound ) must never appear.
        p = sandbox_macos.render_profile(egress=EGRESS, bridges=BRIDGES, is_hook=False)
        self.assertNotIn("(allow network-outbound )", p)
        self.assertNotIn("(allow network-outbound)", p)


class SecurityContent(unittest.TestCase):
    def test_deny_default_and_token_isolation(self):
        for is_hook, egress in ((False, EGRESS), (True, None)):
            p = sandbox_macos.render_profile(egress=egress, bridges=BRIDGES, is_hook=is_hook)
            self.assertTrue(p.startswith("(version 1)"))
            self.assertIn("(deny default)", p)
            self.assertIn("(deny process-info*)", p)
            self.assertNotIn("mach-priv-task-port", p)

    def test_cli_reaches_egress_and_bridges(self):
        # Seatbelt's loopback token is 'localhost' (it rejects the 127.0.0.1 literal); the port is the identity.
        p = sandbox_macos.render_profile(egress=EGRESS, bridges=BRIDGES, is_hook=False)
        self.assertIn(f'(remote ip "localhost:{EGRESS.port}")', p)
        for port in BRIDGES:
            self.assertIn(f'(remote ip "localhost:{port}")', p)

    def test_hook_reaches_bridges_only_never_egress(self):
        p = sandbox_macos.render_profile(egress=None, bridges=BRIDGES, is_hook=True)
        for port in BRIDGES:
            self.assertIn(f'(remote ip "localhost:{port}")', p)
        self.assertNotIn(f'localhost:{EGRESS.port}', p, "a hook must never reach the egress endpoint")


def reference_setup_profile(loopback_port=None):
    """Frozen, independent reference for setup's OWN-run profile. It KEEPS the token-isolation belt (curated
    `sysctl-read` + explicit `(deny process-info*)`) exactly like the agent CLI/hook profiles — the R1 process
    census does NOT run inside this sandbox. The probed CLI (route_probe, SDK, wrapper, CLI) are all
    descendants of the same sandbox-exec, so granting introspection here would hand the code under test the
    observer's capability (RoseCat 7019). Instead trusted setup observes its own descendants OUTSIDE Seatbelt
    over a socketpair (BlueBeaver 7021). Network: none, or exactly the one inherited R1 probe loopback port."""
    net = ([";; network: ONLY the R1 probe's pre-bound loopback port.",
            f'(allow network-outbound (remote ip "localhost:{loopback_port}"))']
           if loopback_port is not None
           else [";; network: NONE — deny-default denies all outbound (setup reaches only its own loopback)."])
    return "\n".join([
        "(version 1)",
        ";; MS6 macOS Seatbelt profile (setup own-run) — generated by sandbox_macos.render_setup_profile. Do not hand-edit.",
        ";; The writable path is the SCRATCHPAD -D parameter; no untrusted value is interpolated into source.",
        "(deny default)",
        "(allow process-fork)",
        "(allow process-exec)",
        "(allow file-read*)",
        f'(allow file-write* (subpath (param "SCRATCHPAD")) {_DEVICES})',
        *net,
        ";; sysctl-read CURATED (MS6.1): never blanket — a blanket allow re-opens kern.procargs2.",
        '(allow sysctl-read (sysctl-name-prefix "hw.")',
        '  (sysctl-name-prefix "kern.os")',
        '  (sysctl-name "kern.ostype")',
        '  (sysctl-name "kern.osrelease")',
        '  (sysctl-name "kern.version")',
        '  (sysctl-name "kern.hostname")',
        '  (sysctl-name "kern.maxproc")',
        '  (sysctl-name "kern.argmax")',
        '  (sysctl-name "kern.ngroups")',
        '  (sysctl-name "kern.usrstack64"))',
        ";; token isolation (MS6.1): explicit process-info deny — the R1 census runs OUTSIDE this sandbox in",
        ";; trusted setup (BlueBeaver 7021), so the probed CLI never gets introspection (RoseCat 7019).",
        "(deny process-info*)",
        "(allow mach-lookup)",
    ]) + "\n"


class SetupProfile(unittest.TestCase):
    def test_matches_reference_no_port(self):
        self.assertEqual(sandbox_macos.render_setup_profile(), reference_setup_profile())

    def test_matches_reference_with_loopback_port(self):
        self.assertEqual(sandbox_macos.render_setup_profile(loopback_port=52999),
                         reference_setup_profile(loopback_port=52999))

    def test_no_port_has_no_network_allow(self):
        self.assertNotIn("(allow network-outbound", sandbox_macos.render_setup_profile(),
                         "without a loopback port, setup has NO network allow (deny-default)")

    def test_loopback_port_is_the_only_outbound(self):
        p = sandbox_macos.render_setup_profile(loopback_port=52999)
        self.assertIn('(allow network-outbound (remote ip "localhost:52999"))', p)
        self.assertEqual(p.count("(allow network-outbound"), 1, "exactly one network allow — the R1 probe port")

    def test_keeps_the_token_isolation_belt_even_for_r1(self):
        # RoseCat 7019: the probed CLI shares this sandbox domain, so it must NOT get introspection. The census
        # moved to trusted setup OUTSIDE Seatbelt (BlueBeaver 7021); the setup profile denies process-info and
        # never blanket-allows sysctl, for both `cli --version` and the R1 run, with or without a loopback port.
        for port in (None, 52999):
            with self.subTest(loopback_port=port):
                p = sandbox_macos.render_setup_profile(loopback_port=port)
                self.assertIn("(deny process-info*)", p, "the token-isolation deny must stay on the setup profile")
                self.assertNotIn("(allow process-info*)", p, "the probed CLI must never get process introspection")
                self.assertNotIn("\n(allow sysctl-read)\n", p, "no blanket sysctl — a blanket allow re-opens procargs2")
                self.assertIn('(allow sysctl-read (sysctl-name-prefix "hw.")', p, "sysctl-read stays curated")
                self.assertIn("(deny default)", p)
                self.assertIn('(subpath (param "SCRATCHPAD"))', p)
                self.assertNotIn("mach-priv-task-port", p)

    def test_bad_loopback_port_refused(self):
        for bad in (0, 65536, -1, "80", 1.5, True):
            with self.assertRaises(ValueError):
                sandbox_macos.render_setup_profile(loopback_port=bad)


