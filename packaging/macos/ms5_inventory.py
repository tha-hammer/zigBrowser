"""Generates the MS5 component inventory (macOS plan rev 17, Behavior MS5.1c).

packaging/macos/universal_components_ms5.json is this module's output, committed; a Linux test fails when the two
differ. The MS1 inventory (universal_components.json) stays the exact MS1 shape and is not touched.

  python3 packaging/macos/ms5_inventory.py --write    regenerate the committed file
  python3 packaging/macos/ms5_inventory.py --check    exit 1 when it drifted
"""
import json
import sys
from pathlib import Path

AGENT = "Frameworks/agent-host"
OUT = Path("packaging/macos/universal_components_ms5.json")


def package_files(repo: Path) -> list[str]:
    """Every regular file of agent/host/zb_agent_host/, relative to agent/host/, no __pycache__ (sorted)."""
    pkg = repo / "agent" / "host" / "zb_agent_host"
    return sorted(str(p.relative_to(pkg.parent)) for p in pkg.rglob("*")
                  if p.is_file() and not p.is_symlink() and "__pycache__" not in p.parts)


def generate(repo: Path) -> dict:
    return {
        "_comment": [
            "MS5 inventory (macOS plan rev 17, Behavior MS5.1c), GENERATED by packaging/macos/ms5_inventory.py:",
            "do not edit by hand. The MS1 components, the python-runtime pair, and the claude-cli fat Mach-O (all",
            "universal2); resources are runtime.json and every file of zb_agent_host/ at its exact path",
            "(byte-identical across the two per-arch trees; nothing else may sit under zb_agent_host/). Layout (a),",
            "the user's decision 2026-10-21: the two arch CLIs are lipo'd into one universal binary at the",
            "site-packages path token.bundled_cli() resolves. The dependency .so's (cffi/pydantic_core/rpds) are",
            "made universal by the strict merge (packaging/macos/merge_universal_tree.py, BlueBeaver); crypto is the",
            "48.0.1 universal2 wheel. The framework is relocated by relocate_python_framework.py (fb437ea).",
        ],
        "components": [
            {"role": "browser", "path_glob": "bin/zigBrowser"},
            {"role": "webview-shim", "path_glob": "Frameworks/libwkwebview_shim.dylib"},
            {"role": "python-runtime", "path_glob": f"{AGENT}/Python.framework/Versions/3.12/bin/python3.12"},
            {"role": "python-runtime", "path_glob": f"{AGENT}/Python.framework/Versions/3.12/Python"},
            {"role": "claude-cli", "path_glob": f"{AGENT}/site-packages/claude_agent_sdk/_bundled/claude"},
        ],
        "resources": [{"role": "runtime-lock", "path": f"{AGENT}/runtime.json"}]
        + [{"role": "agent-host-package", "path": f"{AGENT}/{rel}"} for rel in package_files(repo)],
    }


def render(inv: dict) -> str:
    return json.dumps(inv, indent=2) + "\n"


def main(argv: list[str]) -> int:
    repo = Path(__file__).resolve().parents[2]
    text = render(generate(repo))
    path = repo / OUT
    if argv[1:] == ["--write"]:
        path.write_text(text)
        return 0
    if argv[1:] == ["--check"]:
        return 0 if path.is_file() and path.read_text() == text else 1
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
