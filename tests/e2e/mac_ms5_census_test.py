"""MS5.1c-a, the Linux-provable half (macOS plan rev 17, Behavior MS5.1c; RoseCat 6865, 6871).

- The MS5 inventory, packaging/macos/universal_components_ms5.json, is GENERATED by packaging/macos/ms5_inventory.py
  from the repo: the MS1 components, the python-runtime pair, and resources = runtime.json plus every regular file
  of agent/host/zb_agent_host/ (no __pycache__), each at its exact bundle path. The committed file must equal the
  generated one (drift is red).
- runtime.json exactly identifies the dependency lock and helper-package content.
- The exact-manifest walk over a staged Frameworks/agent-host/zb_agent_host/: every entry is a listed regular file
  or a directory implied by one; a missing file, an extra file, an extra directory, any symlink (also one to an
  outside canary) and any special file (a FIFO) are each a problem. It uses lstat: it never follows the symlink and
  never opens the FIFO (a walk that opened it would block; the test bounds it).

Run like the gate: cd tests/e2e && python3 -m unittest -v mac_ms5_census_test. Unregistered until the green.
"""
import hashlib
import json
import os
import shutil
import sys
import tempfile
import threading
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "packaging" / "macos"))
try:
    import ms5_inventory  # packaging/macos/ms5_inventory.py
except ImportError:
    ms5_inventory = None
try:
    import mac_ms5_census  # tests/e2e/mac_ms5_census.py
except ImportError:
    mac_ms5_census = None

AGENT = "Frameworks/agent-host"
PKG = REPO / "agent" / "host" / "zb_agent_host"


def repo_package_files():
    return sorted(str(p.relative_to(PKG.parent)) for p in PKG.rglob("*")
                  if p.is_file() and not p.is_symlink() and "__pycache__" not in p.parts)


class Inventory(unittest.TestCase):
    def setUp(self):
        if ms5_inventory is None:
            self.fail("packaging/macos/ms5_inventory.py is missing (rev 17 MS5.1c)")

    def test_generated_inventory_has_the_pinned_components_and_every_package_file(self):
        inv = ms5_inventory.generate(REPO)
        globs = [c["path_glob"] for c in inv["components"]]
        self.assertEqual(globs, ["bin/zigBrowser", "Frameworks/libwkwebview_shim.dylib",
                                 f"{AGENT}/Python.framework/Versions/3.12/bin/python3.12",
                                 f"{AGENT}/Python.framework/Versions/3.12/Python",
                                 f"{AGENT}/site-packages/claude_agent_sdk/_bundled/claude"])

    def test_the_claude_cli_role_is_the_universal_binary_at_the_runtime_path(self):
        # layout (a), the user's decision 2026-10-21: the two arch CLIs are lipo'd into one universal Mach-O that
        # lands exactly where token.bundled_cli() resolves it inside the single fat tree (BlueBeaver 7197).
        inv = ms5_inventory.generate(REPO)
        cli = [c for c in inv["components"] if c["role"] == "claude-cli"]
        self.assertEqual(len(cli), 1, "exactly one claude-cli fat Mach-O component")
        self.assertEqual(cli[0]["path_glob"], f"{AGENT}/site-packages/claude_agent_sdk/_bundled/claude")
        paths = [r["path"] for r in inv["resources"]]
        self.assertEqual(paths[0], f"{AGENT}/runtime.json")
        self.assertEqual(paths[1], f"{AGENT}/Python.framework/Versions/3.12/lib/python3.12/site-packages/"
                                   "zb_agent_host_sdk.pth")  # the sdk-path .pth (27a9a62; mac_sdk_pth_test)
        self.assertEqual(paths[2:], [f"{AGENT}/{rel}" for rel in repo_package_files()])
        self.assertTrue(all("__pycache__" not in p for p in paths))
        self.assertGreater(len(paths), 10, "the package's files, not a token list")

    def test_the_committed_inventory_equals_the_generated_one(self):
        committed = REPO / "packaging" / "macos" / "universal_components_ms5.json"
        self.assertTrue(committed.is_file(), "packaging/macos/universal_components_ms5.json is missing")
        self.assertEqual(json.loads(committed.read_text()), ms5_inventory.generate(REPO),
                         "the committed MS5 inventory drifted from agent/host/zb_agent_host/: regenerate it")

    def test_the_ms1_inventory_is_untouched(self):
        ms1 = json.loads((REPO / "packaging" / "macos" / "universal_components.json").read_text())
        self.assertEqual([c["path_glob"] for c in ms1["components"]],
                         ["bin/zigBrowser", "Frameworks/libwkwebview_shim.dylib"])
        self.assertEqual(ms1["resources"], [])


class RuntimeJson(unittest.TestCase):
    def setUp(self):
        if mac_ms5_census is None:
            self.fail("tests/e2e/mac_ms5_census.py is missing (rev 17 MS5.1c)")

    def test_runtime_json_is_exactly_the_installers_bytes(self):
        lock = (REPO / "agent" / "host" / "uv.lock").read_bytes()
        want = ('{"lock_sha256": "%s", "host_sha256": "%s"}\n' %
                (hashlib.sha256(lock).hexdigest(), mac_ms5_census.package_sha256(PKG))).encode()
        self.assertEqual(mac_ms5_census.expected_runtime_json(lock), want)
        self.assertIsNone(mac_ms5_census.runtime_json_problem(want, lock))
        other = ('{"lock_sha256": "%s", "host_sha256": "%s"}\n' %
                 ("0" * 64, mac_ms5_census.package_sha256(PKG))).encode()
        self.assertIsNotNone(mac_ms5_census.runtime_json_problem(other, lock), "another lock_sha256 is red")
        stale = ('{"lock_sha256": "%s", "host_sha256": "%s"}\n' %
                 (hashlib.sha256(lock).hexdigest(), "0" * 64)).encode()
        self.assertIsNotNone(mac_ms5_census.runtime_json_problem(stale, lock), "another host_sha256 is red")
        self.assertIsNotNone(mac_ms5_census.runtime_json_problem(want.rstrip(b"\n"), lock), "no newline is red")


class ExactManifest(unittest.TestCase):
    def setUp(self):
        if mac_ms5_census is None:
            self.fail("tests/e2e/mac_ms5_census.py is missing (rev 17 MS5.1c)")
        self.tmp = Path(tempfile.mkdtemp(prefix="zb-ms5-census-"))
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.root = self.tmp / "tree"
        self.listed = ["zb_agent_host/__init__.py", "zb_agent_host/setup.py", "zb_agent_host/sub/x.py"]
        for rel in self.listed:
            p = self.root / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(rel)

    def problems(self):
        out = []
        t = threading.Thread(target=lambda: out.append(mac_ms5_census.package_problems(self.root, self.listed)), daemon=True)
        t.start()
        t.join(10)
        self.assertFalse(t.is_alive(), "the walk blocked: it opened a FIFO (it must use lstat only)")
        return out[0]

    def test_an_exact_tree_has_no_problem(self):
        self.assertEqual(self.problems(), [])

    def test_a_missing_file_is_red(self):
        (self.root / "zb_agent_host/sub/x.py").unlink()
        self.assertTrue(any("missing" in p and "sub/x.py" in p for p in self.problems()), self.problems())

    def test_an_extra_file_and_an_extra_directory_are_red(self):
        (self.root / "zb_agent_host/evil.py").write_text("x")
        (self.root / "zb_agent_host/emptydir").mkdir()
        probs = self.problems()
        self.assertTrue(any("evil.py" in p for p in probs), probs)
        self.assertTrue(any("emptydir" in p for p in probs), probs)

    def test_a_symlink_to_an_outside_canary_is_red_and_never_followed(self):
        canary = self.tmp / "canary.py"
        canary.write_text("ZB-CANARY")
        (self.root / "zb_agent_host/link.py").symlink_to(canary)
        # A listed path replaced by a symlink is red too.
        (self.root / "zb_agent_host/setup.py").unlink()
        (self.root / "zb_agent_host/setup.py").symlink_to(canary)
        probs = self.problems()
        self.assertTrue(any("link.py" in p and "symlink" in p for p in probs), probs)
        self.assertTrue(any("setup.py" in p and "symlink" in p for p in probs), probs)

    def test_a_fifo_is_red_and_never_opened(self):
        os.mkfifo(self.root / "zb_agent_host/pipe")
        probs = self.problems()
        self.assertTrue(any("pipe" in p and "special" in p for p in probs), probs)

    def test_a_symlinked_package_directory_is_red(self):
        outside = self.tmp / "outside"
        outside.mkdir()
        (outside / "x.py").write_text("zb_agent_host/sub/x.py")
        shutil.rmtree(self.root / "zb_agent_host/sub")
        (self.root / "zb_agent_host/sub").symlink_to(outside)
        probs = self.problems()
        self.assertTrue(any("sub" in p and "symlink" in p for p in probs), probs)


if __name__ == "__main__":
    unittest.main()
